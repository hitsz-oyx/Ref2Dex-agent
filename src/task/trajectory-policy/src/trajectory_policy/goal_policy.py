"""Goal-conditioned low-level policy for the ref2 Stage 1 route.

The policy consumes measured robot/interaction state and a short future goal
made of hand keypoints and object poses.  It deliberately has no future robot
joint state in its public feature contract.  This keeps the interface usable
for the later ``H -> tau_hat -> goal`` route while allowing the first Probe to
use a fixed ground-truth hand/object goal.

The output is a bounded native action.  Coordinates that the Inspire adapter
derives from a parent joint are masked here; the native adapter remains the
single place that applies coupling and final clipping.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Dict

import numpy as np
import torch
from torch import nn


SCHEMA = "ref2dex.goal-conditioned-low-level.v1"
DOF = 18
HAND_POINTS = 11
GOAL_HORIZON = 8
RESIDUAL_GOAL_HORIZON = 24

# These are the coordinates accepted by DExplore's native Inspire action
# adapter.  The remaining six coordinates are generated by its coupling map.
ACTIVE_ACTION = (0, 1, 2, 3, 4, 5, 6, 8, 10, 12, 14, 15)
RESIDUAL_DIM = len(ACTIVE_ACTION)

# q, dq, current hand in the live object frame, future hand goals in that
# frame, future object poses relative to the current object, object velocity,
# previous command, and current object world position.
INPUT_DIM = (
    DOF + DOF + HAND_POINTS * 3 + GOAL_HORIZON * HAND_POINTS * 3
    + GOAL_HORIZON * 12 + 6 + DOF + 3
)

# The retained tau teacher sees a 24-step hand/object future and its own
# previous bounded latent.  It deliberately does not receive future q: the
# nominal q/velocity plan is owned by the shared executor at deployment.
RESIDUAL_INPUT_DIM = (
    DOF + DOF + HAND_POINTS * 3 + RESIDUAL_GOAL_HORIZON * HAND_POINTS * 3
    + RESIDUAL_GOAL_HORIZON * 12 + 6 + RESIDUAL_DIM + 3
)


def _tensor(name: str, value: Any, *, device=None, dtype=None) -> torch.Tensor:
    """Convert an input to a finite floating tensor without hiding errors."""
    if isinstance(value, torch.Tensor):
        result = value
        if device is not None or dtype is not None:
            result = result.to(device=device if device is not None else result.device,
                               dtype=dtype if dtype is not None else result.dtype)
    else:
        result = torch.as_tensor(value, device=device, dtype=dtype or torch.float32)
    if not torch.is_floating_point(result):
        raise TypeError(name + " must be floating point")
    if not torch.isfinite(result).all():
        raise ValueError(name + " must be finite")
    return result


def _check_batch(name: str, value: torch.Tensor, shape) -> None:
    if tuple(value.shape) != tuple(shape):
        raise ValueError("{} must have shape {}, got {}".format(name, shape, tuple(value.shape)))


def _local_points(points: torch.Tensor, center: torch.Tensor,
                  rotation: torch.Tensor) -> torch.Tensor:
    """Express row-vector points in the current object frame."""
    return (points - center.unsqueeze(-2)) @ rotation


def goal_features(q, dq, hand, obj, obj_velocity, previous_action,
                  goal_hand, goal_obj) -> torch.Tensor:
    """Build the bounded Stage 1 student observation.

    Args use a batch dimension.  ``goal_hand[:, k]`` and ``goal_obj[:, k]``
    are the future hand/object targets for k=0..7.  ``q`` is only the live
    measured joint state; no future q is accepted by this function.

    Object-frame quantities use the same row-vector convention as the existing
    retargeting and reference-tracking code.  Object translation is normalized
    in metres, velocity in metres/radians per second, and q/dq/action use the
    established low-level scales.  A final clamp makes malformed but finite
    inputs unable to produce an unbounded MLP input.
    """
    q = _tensor("q", q)
    dq = _tensor("dq", dq, device=q.device, dtype=q.dtype)
    hand = _tensor("hand", hand, device=q.device, dtype=q.dtype)
    obj = _tensor("obj", obj, device=q.device, dtype=q.dtype)
    obj_velocity = _tensor("obj_velocity", obj_velocity, device=q.device, dtype=q.dtype)
    previous_action = _tensor("previous_action", previous_action,
                              device=q.device, dtype=q.dtype)
    goal_hand = _tensor("goal_hand", goal_hand, device=q.device, dtype=q.dtype)
    goal_obj = _tensor("goal_obj", goal_obj, device=q.device, dtype=q.dtype)

    if q.ndim != 2:
        raise ValueError("q must have a batch dimension")
    batch = q.shape[0]
    _check_batch("q", q, (batch, DOF))
    _check_batch("dq", dq, (batch, DOF))
    _check_batch("hand", hand, (batch, HAND_POINTS, 3))
    _check_batch("obj", obj, (batch, 4, 4))
    _check_batch("obj_velocity", obj_velocity, (batch, 6))
    _check_batch("previous_action", previous_action, (batch, DOF))
    _check_batch("goal_hand", goal_hand, (batch, GOAL_HORIZON, HAND_POINTS, 3))
    _check_batch("goal_obj", goal_obj, (batch, GOAL_HORIZON, 4, 4))

    rotation = obj[:, :3, :3]
    center = obj[:, :3, 3]
    local_hand = _local_points(hand, center, rotation)
    # Use an explicit einsum for the row-vector convention so the goal horizon
    # is not accidentally broadcast against the current hand point dimension.
    local_goal_hand = torch.einsum(
        "btkj,bji->btki", goal_hand - center[:, None, None], rotation
    )
    goal_center = goal_obj[:, :, :3, 3]
    goal_rotation = goal_obj[:, :, :3, :3]
    relative_translation = (goal_center - center[:, None]) @ rotation
    relative_rotation = rotation[:, None].transpose(-1, -2) @ goal_rotation
    goal_object = torch.cat((relative_translation / 0.1,
                             relative_rotation.reshape(batch, GOAL_HORIZON, 9)), -1)

    values = torch.cat((
        q,
        dq / 8.0,
        local_hand.reshape(batch, -1) / 0.1,
        local_goal_hand.reshape(batch, -1) / 0.1,
        goal_object.reshape(batch, -1),
        obj_velocity / 2.0,
        previous_action,
        center / 0.1,
    ), dim=-1).clamp(-20.0, 20.0)
    if values.shape != (batch, INPUT_DIM) or not torch.isfinite(values).all():
        raise FloatingPointError("invalid goal-conditioned features")
    return values


def residual_goal_features(q, dq, hand, obj, obj_velocity, previous_residual,
                          goal_hand, goal_obj) -> torch.Tensor:
    """Build the retained-tau-compatible residual-policy observation.

    ``previous_residual`` is the previous *bounded* 12-D latent, i.e.
    ``tanh(raw_latent[t-1])``.  The 24-step hand/object goal horizon matches
    :class:`GoalConditionedExecutor`; no future robot joint state is accepted.
    """
    q = _tensor("q", q)
    dq = _tensor("dq", dq, device=q.device, dtype=q.dtype)
    hand = _tensor("hand", hand, device=q.device, dtype=q.dtype)
    obj = _tensor("obj", obj, device=q.device, dtype=q.dtype)
    obj_velocity = _tensor("obj_velocity", obj_velocity, device=q.device, dtype=q.dtype)
    previous_residual = _tensor("previous_residual", previous_residual,
                                device=q.device, dtype=q.dtype)
    goal_hand = _tensor("goal_hand", goal_hand, device=q.device, dtype=q.dtype)
    goal_obj = _tensor("goal_obj", goal_obj, device=q.device, dtype=q.dtype)

    if q.ndim != 2:
        raise ValueError("q must have a batch dimension")
    batch = q.shape[0]
    _check_batch("q", q, (batch, DOF))
    _check_batch("dq", dq, (batch, DOF))
    _check_batch("hand", hand, (batch, HAND_POINTS, 3))
    _check_batch("obj", obj, (batch, 4, 4))
    _check_batch("obj_velocity", obj_velocity, (batch, 6))
    _check_batch("previous_residual", previous_residual, (batch, RESIDUAL_DIM))
    _check_batch("goal_hand", goal_hand,
                 (batch, RESIDUAL_GOAL_HORIZON, HAND_POINTS, 3))
    _check_batch("goal_obj", goal_obj,
                 (batch, RESIDUAL_GOAL_HORIZON, 4, 4))

    rotation = obj[:, :3, :3]
    center = obj[:, :3, 3]
    local_hand = _local_points(hand, center, rotation)
    local_goal_hand = torch.einsum(
        "btkj,bji->btki", goal_hand - center[:, None, None], rotation
    )
    goal_center = goal_obj[:, :, :3, 3]
    goal_rotation = goal_obj[:, :, :3, :3]
    relative_translation = (goal_center - center[:, None]) @ rotation
    relative_rotation = rotation[:, None].transpose(-1, -2) @ goal_rotation
    goal_object = torch.cat((relative_translation / 0.1,
                             relative_rotation.reshape(batch, RESIDUAL_GOAL_HORIZON, 9)), -1)

    values = torch.cat((
        q,
        dq / 8.0,
        local_hand.reshape(batch, -1) / 0.1,
        local_goal_hand.reshape(batch, -1) / 0.1,
        goal_object.reshape(batch, -1),
        obj_velocity / 2.0,
        previous_residual,
        center / 0.1,
    ), dim=-1).clamp(-20.0, 20.0)
    if values.shape != (batch, RESIDUAL_INPUT_DIM) or not torch.isfinite(values).all():
        raise FloatingPointError("invalid residual goal-conditioned features")
    return values


@dataclass(frozen=True)
class Standardizer:
    """Train-only feature standardization with a strictly positive scale."""

    mean: np.ndarray
    scale: np.ndarray

    def __post_init__(self):
        mean = np.asarray(self.mean, dtype=np.float32)
        scale = np.asarray(self.scale, dtype=np.float32)
        if mean.shape != (INPUT_DIM,) or scale.shape != (INPUT_DIM,):
            raise ValueError("standardizer must contain one value per input feature")
        if not np.isfinite(mean).all() or not np.isfinite(scale).all() or (scale <= 0).any():
            raise ValueError("standardizer values must be finite and positive")
        object.__setattr__(self, "mean", mean)
        object.__setattr__(self, "scale", scale)

    @classmethod
    def fit(cls, values: np.ndarray) -> "Standardizer":
        values = np.asarray(values, dtype=np.float32)
        if values.ndim != 2 or values.shape[1] != INPUT_DIM or len(values) == 0:
            raise ValueError("fit expects a non-empty [N, INPUT_DIM] matrix")
        if not np.isfinite(values).all():
            raise ValueError("cannot fit nonfinite features")
        mean = values.mean(axis=0, dtype=np.float64).astype(np.float32)
        scale = values.std(axis=0, dtype=np.float64).astype(np.float32)
        return cls(mean, np.maximum(scale, 1e-4).astype(np.float32))

    def encode(self, values) -> np.ndarray:
        values = np.asarray(values, dtype=np.float32)
        if values.shape[-1] != INPUT_DIM or not np.isfinite(values).all():
            raise ValueError("invalid features for standardization")
        result = (values - self.mean) / self.scale
        if not np.isfinite(result).all():
            raise FloatingPointError("nonfinite standardized features")
        return result.astype(np.float32, copy=False)

    def decode(self, values) -> np.ndarray:
        values = np.asarray(values, dtype=np.float32)
        if values.shape[-1] != INPUT_DIM or not np.isfinite(values).all():
            raise ValueError("invalid standardized features")
        return (values * self.scale + self.mean).astype(np.float32, copy=False)

    def as_dict(self) -> Dict[str, list]:
        return {"mean": self.mean.tolist(), "scale": self.scale.tolist()}


